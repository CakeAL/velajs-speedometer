// Run from this repository inside the Speedometer checkout to regenerate the wire fixture.
import { writeFile, mkdir } from 'node:fs/promises'
import { load, fakeFiles } from '../../tests/helpers.mjs'
const { createTrackProtocol, PROTOCOL, VERSION } = await load('../src/common/track-protocol.js')
const { TRACK_DIR } = await load('../src/common/files.js')
const name = 'track-2026-10-09T19-33-50-183+0800.gpx'
const gpx = '<?xml version="1.0" encoding="UTF-8"?>\n<gpx version="1.1"><trk><name>含海拔的轨迹</name><trkseg>\n' +
  Array.from({ length: 30 }, (_, i) => `<trkpt lat="31.${String(i).padStart(6, '0')}" lon="121.500000"><ele>${i - 12}.50</ele><time>2026-10-09T11:33:${String(i).padStart(2, '0')}Z</time></trkpt>\n`).join('') +
  '</trkseg></trk></gpx>\n'
const fs = fakeFiles(uri => uri.replace('/track-', '//track-'))
fs.data.set(TRACK_DIR, null)
fs.data.set(TRACK_DIR + name, gpx)
const handle = createTrackProtocol(fs.api, () => null)
let sequence = 0
const call = (op, fields = {}) => handle({ protocol: PROTOCOL, version: VERSION, id: 'fixture-' + ++sequence, op, ...fields })
const hello = await call('hello')
const list = await call('list')
const track = list.result.files[0]
const chunks = []
let offset = 0
do {
  const chunk = await call('read', { name, etag: track.etag, offset })
  if (!chunk.ok) throw new Error(JSON.stringify(chunk))
  chunks.push(chunk)
  offset = chunk.result.nextOffset
} while (offset < track.bytes)
const changed = await call('read', { name, etag: 'changed', offset: 0 })
const deleted = await call('delete', { name, etag: track.etag })
const deletedAgain = await call('delete', { name, etag: track.etag })
const dir = new URL('../tests/fixtures/', import.meta.url)
await mkdir(dir, { recursive: true })
await writeFile(new URL('watch.json', dir), JSON.stringify({ hello, list, chunks, changed, deleted, deletedAgain, gpx }, null, 2) + '\n')
console.log(`Watch fixture: ${track.bytes} bytes, ${chunks.length} chunks, generated by the actual JS server`)
